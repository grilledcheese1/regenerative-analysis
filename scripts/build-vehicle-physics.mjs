// Build src/fixtures/vehicle-physics.json: the physics of every person's own car, from simulated_user_data.
// Run with `node scripts/build-vehicle-physics.mjs` after regenerating simulated_user_data; the app only reads the JSON.
// All values are approximate teaching numbers, not manufacturer specs.

import { readFileSync, writeFileSync } from "node:fs";

const SEED = "simulated_user_data/reference/vehicles.seed.json";
const OUT = "src/fixtures/vehicle-physics.json";

const seed = JSON.parse(readFileSync(SEED, "utf8"));
const list = Object.values(seed).find(Array.isArray);
const cars = Object.fromEntries(list.map((v) => [v.id, v]));

// The three hand-written customers have no row in simulated_user_data, so they get the closest car.
// Kai's 2021 RAV4 is gasoline and the dataset has no gasoline RAV4, so it is added here with the same kind of rounded specs.
cars.toyota_rav4_2021 = {
  id: "toyota_rav4_2021", make: "Toyota", model: "RAV4", year: 2021, powertrain: "ice",
  massKg: 1620, cd: 0.31, frontalAreaM2: 2.65, crr: 0.011, regenEta: 0, maxRegenKw: 0, drivenAxleWeight: 0.55, batteryKwh: 0,
};
const CURATED = {
  maria: { vehicleId: "toyota_camry_hybrid_2025", extraMassKg: 80 },
  devon: { vehicleId: "toyota_corolla_2025", extraMassKg: 80 },
  kai: { vehicleId: "toyota_rav4_2021", extraMassKg: 160 },
};

// A gasoline car recovers no braking energy, so its regen replay uses the hybrid a driver of that car would consider.
const HYBRID_COUNTERPART = {
  toyota_corolla_2025: "toyota_corolla_hybrid_2025",
  toyota_rav4_2021: "toyota_rav4_hybrid_2025",
  toyota_4runner_2025: "toyota_highlander_hybrid_2025",
  toyota_tundra_2025: "toyota_tundra_hybrid_2025",
  toyota_tacoma_2025: "ford_maverick_hybrid_2025",
  chevy_silverado_2025: "toyota_tundra_hybrid_2025",
  honda_civic_2025: "honda_civic_hybrid_2025",
  hyundai_elantra_2025: "toyota_corolla_hybrid_2025",
  ford_f150_ecoboost_2025: "toyota_tundra_hybrid_2025",
  subaru_outback_2025: "toyota_rav4_hybrid_2025",
  mazda_cx5_2025: "toyota_rav4_hybrid_2025",
};

const people = { ...CURATED };
const generated = JSON.parse(readFileSync("src/fixtures/people.generated.json", "utf8")).personas;
for (const p of generated) {
  const user = JSON.parse(readFileSync(`simulated_user_data/users/${p.id.replace("-", "_")}.json`, "utf8"));
  people[p.id] = { vehicleId: user.vehicle.vehicleId, extraMassKg: user.load?.typicalExtraMassKg ?? 0 };
}

const used = new Set();
for (const p of Object.values(people)) {
  const car = cars[p.vehicleId];
  if (!car) throw new Error(`unknown vehicle ${p.vehicleId}`);
  used.add(p.vehicleId);
  if (car.powertrain === "ice") {
    const h = HYBRID_COUNTERPART[p.vehicleId];
    if (!h || !cars[h]) throw new Error(`no hybrid counterpart for ${p.vehicleId}`);
    p.replayVehicleId = h;
    used.add(h);
  } else {
    p.replayVehicleId = p.vehicleId;
  }
}

const vehicles = Object.fromEntries(
  [...used].sort().map((id) => {
    const v = cars[id];
    return [id, {
      label: `${v.make} ${v.model}`,
      powertrain: v.powertrain,
      massKg: v.massKg,
      dragCoefficient: v.cd,
      frontalAreaM2: v.frontalAreaM2,
      rollingResistance: v.crr,
      regenEfficiency: v.regenEta,
      maxRegenKw: v.maxRegenKw,
      drivenAxleWeightShare: v.drivenAxleWeight,
      batteryKwh: v.batteryKwh,
    }];
  }),
);

writeFileSync(OUT, JSON.stringify({ note: "Approximate teaching physics, generated by scripts/build-vehicle-physics.mjs. Not manufacturer data.", vehicles, people }, null, 2) + "\n");
console.log(`${Object.keys(vehicles).length} vehicles, ${Object.keys(people).length} people -> ${OUT}`);
